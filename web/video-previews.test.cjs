const { chromium } = require('playwright');
const sharp = require('sharp');
const assert = require('node:assert/strict');
const { writeFile, readFile } = require('node:fs/promises');
const path = require('node:path');
const base = 'http://127.0.0.1:4173';
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const checks = [], errors = [], api = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 960 }, reducedMotion: 'reduce' });
    context.on('request', r => { if (new URL(r.url()).pathname.startsWith('/api/')) api.push(r.url()); });
    const account = await context.newPage(); await account.goto(base + '/money.html');
    await account.locator('#wallet-private').click(); await account.locator('#wallet-content').waitFor();
    const snapshot = () => account.evaluate(async () => JSON.stringify(await (await import('/chat-store.js')).readState()));
    const before = await snapshot();
    const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/');
    await page.waitForFunction(() => document.querySelector('#home-cache-status').textContent.startsWith('Homepage saved'));
    await page.waitForFunction(() => document.querySelector('#hero-preview').readyState >= 2);
    assert.equal(await page.locator('iframe').count(), 0);
    assert.equal(await page.locator('.video-controls, .video-toggle, .scene-step, .hero-trace').count(), 0, 'Previews use direct gestures without playback buttons or a decorative trace');
    assert(await page.locator('#hero-preview').evaluate(v => v.paused && v.muted && v.loop && !v.controls && v.videoWidth === 1200 && v.videoHeight === 1320));
    await page.locator('#hero-preview').press('Space');
    await page.waitForFunction(() => document.querySelector('#hero-preview').currentTime > .3);
    await page.locator('#hero-preview').press('Space');
    assert(await page.locator('#hero-preview').evaluate(v => v.paused));
    // The status pill uses actual application styles, including the dark fix.
    const contrast = await account.evaluate(() => {
      document.documentElement.dataset.theme = 'dark';
      const pill = document.createElement('p'); pill.className = 'trade-state'; pill.textContent = 'Awaiting online confirmation'; document.body.append(pill);
      const css = getComputedStyle(pill), result = { color: css.color, background: css.backgroundColor }; pill.remove(); return result;
    });
    assert.deepEqual(contrast, { color: 'rgb(237, 243, 233)', background: 'rgb(43, 68, 50)' });
    checks.push('actual MP4 decodes at 1200×1320; reduced motion starts paused; play/pause works; dark payment status uses readable contrast');
    for (const theme of ['dark', 'light']) {
      await page.getByRole('button', { name: `Switch to ${theme} theme` }).click();
      assert((await page.locator('#hero-preview').getAttribute('src')).endsWith(`chat-${theme}.mp4`));
      for (const view of ['chat', 'profile', 'wallet']) {
        await page.locator('#view-' + view).click();
        await page.locator('#product-preview').scrollIntoViewIfNeeded();
        await page.waitForFunction(() => document.querySelector('#product-preview').readyState >= 2);
        assert((await page.locator('#product-preview').getAttribute('src')).endsWith(`${view}-${theme}.mp4`));
        assert(await page.locator('#product-preview').evaluate(v => v.duration > 5 && !v.error));
        await page.locator('#product-preview').press('Space');
        await page.waitForFunction(() => document.querySelector('#product-preview').currentTime > .25);
        if (!(await page.locator('#product-preview').evaluate(v => v.paused))) await page.locator('#product-preview').press('Space');
        const pixel = async input => [...await sharp(input).resize(600,660).extract({left:300,top:20,width:1,height:1}).removeAlpha().raw().toBuffer()];
        const actual = await pixel(await page.locator('#product-preview').screenshot());
        const expected = await pixel(path.join(__dirname, `public/previews/${view}-${theme}.webp`));
        assert(actual.every((value,i)=>Math.abs(value-expected[i])<=6), `Video color differs from its source poster: ${view} ${theme}`);
      }
      await page.setViewportSize({ width: 375, height: 812 });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.locator('#product-preview').evaluate(v => new Promise(resolve => { v.pause(); v.requestVideoFrameCallback(() => requestAnimationFrame(() => requestAnimationFrame(resolve))); v.currentTime = 2; }));
      assert(Math.abs(await page.locator('#product-preview').evaluate(v=>v.currentTime)-2)<.1, 'Seek must land on the requested frame');
      await page.locator('#product-preview').evaluate(v => v.blur());
      await page.locator('#product-preview').locator('..').screenshot({ path: path.join(__dirname, `evidence/video-preview-${theme}.png`) });
      await page.setViewportSize({ width: 1280, height: 960 });
    }
    checks.push('all six light/dark videos play and retain source background colors; narrow layouts fit');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.getByRole('button', { name: 'Motion on', exact: true }).waitFor();
    await page.locator('#product-preview').press('Space');
    await page.waitForFunction(() => !document.querySelector('#product-preview').paused);
    await page.evaluate(() => scrollTo(0, 0));
    await page.waitForFunction(() => document.querySelector('#product-preview').paused);
    checks.push('playing video pauses when it leaves the viewport');
    await page.getByRole('button', { name: 'Switch to dark theme' }).click();
    await account.reload(); await account.locator('#wallet-content').waitFor();
    assert.equal(await account.locator('html').getAttribute('data-theme'), 'dark');
    assert.equal(await account.locator('#near-total').textContent(), '0');
    assert.equal(await snapshot(), before);
    await account.locator('#show-profile').click(); await account.locator('#edit-profile[open]').waitFor();
    assert(await account.locator('dialog[open]').evaluate(n => getComputedStyle(n).backgroundColor === 'rgb(32, 56, 43)'));
    await account.getByRole('button', { name: 'Close profile', exact: true }).click();
    await account.evaluate(async () => (await import('/save-offline.js')).saveOffline());
    checks.push('actual wallet/profile follows the chosen theme without changing identity or balances');
    await context.setOffline(true); await page.reload();
    await page.locator('#view-profile').click(); await page.locator('#product-preview').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelector('#product-preview').readyState >= 2);
    await page.locator('#product-preview').evaluate(v => { v.currentTime = 3; });
    await page.waitForFunction(() => !document.querySelector('#product-preview').seeking && Math.abs(document.querySelector('#product-preview').currentTime-3)<.1);
    if (await page.locator('#product-preview').evaluate(v => v.paused)) await page.locator('#product-preview').press('Space');
    await page.waitForFunction(() => document.querySelector('#product-preview').currentTime > 3.2);
    await page.getByRole('button', { name: 'Switch to light theme' }).click();
    await page.locator('#view-chat').click(); await page.waitForFunction(() => document.querySelector('#product-preview').readyState >= 2);
    assert((await page.locator('#product-preview').getAttribute('src')).endsWith('chat-light.mp4'));
    await account.reload(); await account.locator('#wallet-content').waitFor(); assert.equal(await snapshot(), before);
    assert.deepEqual(api, []); assert.deepEqual(errors, []);
    checks.push('offline video playback, seeking and theme switching work; cached wallet identity remains unchanged');
    const scenes = JSON.parse(await readFile(path.join(__dirname,'public/previews/timelines.json'))).chat;
    const preview = page.locator('#product-preview');
    if (!await preview.evaluate(v=>v.paused)) await preview.press('Space');
    await preview.evaluate(v=>{v.currentTime=0});
    await preview.focus(); await preview.press('ArrowRight');
    await page.waitForFunction(t=>Math.abs(document.querySelector('#product-preview').currentTime-t)<.1, scenes[1].start+.05);
    const screen = preview.locator('..');
    const tap = async fraction => { const box=await screen.boundingBox(); await page.mouse.click(box.x+box.width*fraction,box.y+box.height*.45); };
    await tap(.2); await page.waitForFunction(()=>document.querySelector('#product-preview').currentTime<.15);
    await tap(.8); await page.waitForFunction(t=>Math.abs(document.querySelector('#product-preview').currentTime-t)<.1,scenes[1].start+.05);
    await tap(.8); await page.waitForFunction(t=>Math.abs(document.querySelector('#product-preview').currentTime-t)<.1,scenes[2].start+.05);
    await tap(.8); await tap(.8); await page.waitForFunction(()=>document.querySelector('#product-preview').currentTime<.15);
    await tap(.2); assert(await preview.evaluate(v=>v.currentTime<.15), 'Back at the first scene stays at the start');
    assert.equal(await page.locator('.video-controls,.video-toggle,.scene-step,.hero-trace').count(),0);
    await preview.press('Space'); await page.waitForFunction(()=>!document.querySelector('#product-preview').paused);
    const box=await screen.boundingBox();
    await page.mouse.move(box.x+box.width*.75,box.y+box.height*.45); await page.mouse.down();
    await page.waitForFunction(()=>document.querySelector('#product-preview').paused);
    const heldTime=await preview.evaluate(v=>v.currentTime); await page.waitForTimeout(450);
    assert.equal(await preview.evaluate(v=>v.currentTime),heldTime,'Holding freezes the frame');
    await page.mouse.up(); await page.waitForFunction(()=>!document.querySelector('#product-preview').paused);
    assert(Math.abs(await preview.evaluate(v=>v.currentTime)-heldTime)<.3,'Releasing a hold resumes without changing scene');
    await preview.press('Space'); await page.waitForFunction(()=>document.querySelector('#product-preview').paused);
    const pausedTime=await preview.evaluate(v=>v.currentTime);
    await page.mouse.down(); await page.waitForTimeout(350); await page.mouse.up();
    assert(await preview.evaluate(v=>v.paused),'Holding preserves an already paused preview');
    assert.equal(await preview.evaluate(v=>v.currentTime),pausedTime);
    await page.mouse.down(); await page.mouse.move(box.x+box.width*.35,box.y+box.height*.65); await page.mouse.up();
    assert.equal(await preview.evaluate(v=>v.currentTime),pausedTime,'Dragging does not navigate');
    await preview.press('Tab'); await page.keyboard.press('Shift+Tab');
    assert(await preview.evaluate(v=>v.matches(':focus-visible') && getComputedStyle(v).outlineStyle==='solid'),'Keyboard focus stays visible');
    checks.push('left/right taps and keyboard navigation work offline; hold pauses without seeking, drag is ignored, and no playback buttons or dotted trace remain');
    const touchContext = await browser.newContext({ viewport:{width:390,height:844}, isMobile:true, hasTouch:true, deviceScaleFactor:2 });
    const touchPage = await touchContext.newPage();
    touchPage.on('pageerror',e=>errors.push(e.message));
    await touchPage.goto(base+'/');
    await touchPage.waitForFunction(()=>document.querySelector('#home-cache-status').textContent.startsWith('Homepage saved'));
    const touchVideo=touchPage.locator('#hero-preview');
    await touchVideo.scrollIntoViewIfNeeded();
    await touchPage.waitForFunction(()=>document.querySelector('#hero-preview').readyState>=2 && !document.querySelector('#hero-preview').paused);
    const touchBox=await touchVideo.boundingBox(), tx=touchBox.x+touchBox.width*.8, ty=touchBox.y+touchBox.height*.45;
    await touchPage.touchscreen.tap(tx,ty);
    await touchPage.waitForFunction(t=>Math.abs(document.querySelector('#hero-preview').currentTime-t)<.3,scenes[1].start+.05);
    await touchPage.touchscreen.tap(touchBox.x+touchBox.width*.2,ty);
    await touchPage.waitForFunction(()=>document.querySelector('#hero-preview').currentTime<.3);
    const cdp=await touchContext.newCDPSession(touchPage);
    const touch=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points});
    const point=(x,y)=>({x,y,id:1,radiusX:5,radiusY:5});
    await touch('touchStart',[point(tx,ty)]);
    await touchPage.waitForFunction(()=>document.querySelector('#hero-preview').paused);
    const touchTime=await touchVideo.evaluate(v=>v.currentTime); await touchPage.waitForTimeout(450);
    assert.equal(await touchVideo.evaluate(v=>v.currentTime),touchTime);
    await touch('touchEnd',[]);
    await touchPage.waitForFunction(()=>!document.querySelector('#hero-preview').paused);
    assert(Math.abs(await touchVideo.evaluate(v=>v.currentTime)-touchTime)<.3);
    await touch('touchStart',[point(tx,ty)]); await touch('touchCancel',[]);
    await touchPage.waitForFunction(()=>!document.querySelector('#hero-preview').paused);
    const scrollBefore=await touchPage.evaluate(()=>scrollY), dragTime=await touchVideo.evaluate(v=>v.currentTime);
    await touch('touchStart',[point(tx,ty)]);
    for (const distance of [20,50,90,140]) { await touch('touchMove',[point(tx,ty-distance)]); await touchPage.waitForTimeout(25); }
    await touch('touchEnd',[]);
    await touchPage.waitForFunction(y=>scrollY>y+20,scrollBefore);
    assert(Math.abs(await touchVideo.evaluate(v=>v.currentTime)-dragTime)<1,'Vertical touch scroll must not change scenes');
    assert.deepEqual(errors,[]); await touchContext.close();
    checks.push('Edge touch emulation: both tap directions, press-and-hold, cancellation and vertical scrolling work without accidental scene changes');
    const result = { checkedAt: new Date().toISOString(), browser: await browser.version(), passed: checks.length, failed: 0, apiRequests: api.length, checks };
    await writeFile(path.join(__dirname, 'video-preview-results.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
